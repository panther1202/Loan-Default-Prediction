/**
 * Lending policy: the rate card, the approve/deny threshold, and denial suggestions.
 *
 * Everything here is a decision from docs/adr/0007-approval-decision-and-suggestions.md, not
 * a measurement — which is why the numbers are constants in this file rather than reads from
 * `model_params.json`. The band *breakpoints* are the exception: they are quintiles of the
 * observed CreditScore distribution and so are read from the export, which keeps the card
 * pointing at real quintiles after a dataset change instead of at stale ones.
 *
 * Direction matters twice over: `P(default)` is a risk score, so lower approves; and the
 * card is never searched for a rate that would rescue an applicant, because on this model a
 * higher rate strictly raises predicted default (ADR-0007 Context).
 */

import { CREDIT_BAND_BREAKPOINTS, CREDIT_SCORE_OBSERVED_RANGE } from "./params.js";
import {
  type ApplicantInput,
  type Contribution,
  attribute,
  buildFeatureVector,
  score,
  validateApplicant,
  withoutProtectedFeatures,
} from "./pipeline.js";

/** `P(default) <= 0.37` approves. Panth's risk appetite, chosen over sklearn's default 0.50. */
export const APPROVAL_THRESHOLD = 0.37;

/** One APR per credit band, lowest band first. 400bps of spread, no term dimension. */
export const RATE_CARD_APR = [11.0, 10.0, 9.0, 8.0, 7.0];

/** The terms on offer, matching the dataset's observed LoanTerm values exactly. */
export const TERM_OPTIONS = [12, 24, 36, 48, 60];

/**
 * The only features a denial may suggest changing. `LoanTerm` is deliberately absent:
 * extending it flips 0.9% of denials on this model and only shortening helps, which is not
 * advice worth giving. `Age`, `MaritalStatus`, `EmploymentType` and `Education` are never
 * suggestible, however mathematically effective they would be.
 */
export const SUGGESTION_ALLOW_LIST = ["LoanAmount", "HasCoSigner", "CreditScore"];

export type Decision = "approve" | "deny";

export interface Suggestion {
  feature: string;
  currentValue: number | string;
  suggestedValue: number | string;
  /** `P(default)` after applying this change alone, everything else held fixed. */
  projectedProbability: number;
}

export interface Assessment {
  applicant: ApplicantInput;
  band: number;
  assignedApr: number;
  termMonths: number;
  probability: number;
  logit: number;
  decision: Decision;
  /** Full attribution, for logs and tests. */
  contributions: Contribution[];
  /** The protected-filtered view — the only attribution an explanation may be built from. */
  citableContributions: Contribution[];
  suggestions: Suggestion[];
  disclaimer: string;
}

export const DISCLAIMER =
  "This is a learning simulation. The decision and explanation are generated by a " +
  "demonstration system and are not legally reviewed adverse-action notice language.";

/** Band index, 0 (lowest scores) to 4. Each exported breakpoint is the floor of its band. */
export function creditBand(creditScore: number): number {
  let band = 0;
  for (const breakpoint of CREDIT_BAND_BREAKPOINTS) {
    if (creditScore >= breakpoint) band += 1;
  }
  return band;
}

export function assignedApr(creditScore: number): number {
  const apr = RATE_CARD_APR[creditBand(creditScore)];
  if (apr === undefined) {
    throw new Error("rate card has no APR for this band — check RATE_CARD_APR against the export");
  }
  return apr;
}

export function decide(probability: number): Decision {
  return probability <= APPROVAL_THRESHOLD ? "approve" : "deny";
}

/** Score one applicant end to end: assign the rate, score, decide, attribute, suggest. */
export function assess(input: unknown): Assessment {
  const applicant = validateApplicant(input);
  const creditScore = applicant.CreditScore as number;
  const apr = assignedApr(creditScore);
  const vector = buildFeatureVector(applicant, apr);
  const { logit, probability } = score(vector);
  const decision = decide(probability);
  const contributions = attribute(vector);

  return {
    applicant,
    band: creditBand(creditScore),
    assignedApr: apr,
    termMonths: applicant.LoanTerm as number,
    probability,
    logit,
    decision,
    contributions,
    citableContributions: withoutProtectedFeatures(contributions),
    suggestions: decision === "deny" ? computeSuggestions(applicant) : [],
    disclaimer: DISCLAIMER,
  };
}

function probabilityWith(applicant: ApplicantInput, override: Record<string, number | string>) {
  const candidate = { ...applicant, ...override };
  const vector = buildFeatureVector(candidate, assignedApr(candidate.CreditScore as number));
  return score(vector).probability;
}

/**
 * Smallest move of one numeric lever, from `current` toward `limit`, that gets P(default)
 * under the threshold. Returns undefined if even the far end does not.
 *
 * ponytail: coarse scan then bisect, over a full re-score each step, rather than solving for
 * the feature directly. Two reasons the closed form would be wrong: LoanAmount moves
 * EstimatedEMI and Payment_to_Income_Ratio as well as its own term — and EstimatedEMI carries
 * a *negative* coefficient on this model, so the levers partly fight each other and the
 * response is not guaranteed monotonic; CreditScore can additionally cross a band boundary
 * and change the assigned APR. The scan finds the first crossing rather than assuming there
 * is only one. ~60 evaluations of 26 multiplies, so the cost is irrelevant.
 */
function firstCrossing(
  evaluate: (value: number) => number,
  current: number,
  limit: number,
  steps = 50,
): { value: number; probability: number } | undefined {
  if (evaluate(limit) > APPROVAL_THRESHOLD) return undefined;

  const stride = (limit - current) / steps;
  let previous = current;
  for (let i = 1; i <= steps; i += 1) {
    const value = current + stride * i;
    if (evaluate(value) <= APPROVAL_THRESHOLD) {
      let low = previous;
      let high = value;
      for (let j = 0; j < 40; j += 1) {
        const mid = (low + high) / 2;
        if (evaluate(mid) <= APPROVAL_THRESHOLD) high = mid;
        else low = mid;
      }
      return { value: high, probability: evaluate(high) };
    }
    previous = value;
  }
  return undefined;
}

/**
 * Suggestions are computed, never guessed. Returned in allow-list order.
 *
 * ponytail: ADR-0007 asks for "the 1-2 most feasible" suggestions but defines no feasibility
 * measure, and inventing one (is a co-signer easier to find than a smaller loan?) would be a
 * policy decision made in code. This returns every lever that works, in allow-list order, and
 * leaves the caller to take the first two. Upgrade path: a measured or stated ranking in
 * ADR-0007, applied here.
 */
export function computeSuggestions(applicant: ApplicantInput): Suggestion[] {
  const suggestions: Suggestion[] = [];

  const currentAmount = applicant.LoanAmount as number;
  const amount = firstCrossing(
    (value) => probabilityWith(applicant, { LoanAmount: value }),
    currentAmount,
    0,
  );
  if (amount) {
    // Round away from the boundary so the figure quoted to the applicant still clears it.
    const rounded = Math.floor(amount.value / 100) * 100;
    const projected = probabilityWith(applicant, { LoanAmount: rounded });
    const usable = projected <= APPROVAL_THRESHOLD;
    suggestions.push({
      feature: "LoanAmount",
      currentValue: currentAmount,
      suggestedValue: usable ? rounded : amount.value,
      projectedProbability: usable ? projected : amount.probability,
    });
  }

  if (applicant.HasCoSigner !== "Yes") {
    const projected = probabilityWith(applicant, { HasCoSigner: "Yes" });
    if (projected <= APPROVAL_THRESHOLD) {
      suggestions.push({
        feature: "HasCoSigner",
        currentValue: applicant.HasCoSigner as string,
        suggestedValue: "Yes",
        projectedProbability: projected,
      });
    }
  }

  const currentScore = applicant.CreditScore as number;
  const highestObserved = CREDIT_SCORE_OBSERVED_RANGE[1];
  if (currentScore < highestObserved) {
    const credit = firstCrossing(
      (value) => probabilityWith(applicant, { CreditScore: value }),
      currentScore,
      highestObserved,
    );
    if (credit) {
      const rounded = Math.min(Math.ceil(credit.value), highestObserved);
      const projected = probabilityWith(applicant, { CreditScore: rounded });
      const usable = projected <= APPROVAL_THRESHOLD;
      suggestions.push({
        feature: "CreditScore",
        currentValue: currentScore,
        suggestedValue: usable ? rounded : credit.value,
        projectedProbability: usable ? projected : credit.probability,
      });
    }
  }

  return suggestions;
}
